const SCALE = 0.4826;
function point(u, v) {
  return [(u - 780) * SCALE, (v - 370) * SCALE];
}
const sites = [];
function site(id, name, u, v, w, d, h, style, year, story) {
  const [x, z] = point(u, v);
  const s = { id, name, u, v, x, z, w: w * SCALE, d: d * SCALE, h, style, year, story };
  sites.push(s);
  return s;
}
