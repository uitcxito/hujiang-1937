// Rebuild the portable page using only Node.js standard modules.
const fs = require("node:fs");
const path = require("node:path");
const read = (file) => fs.readFileSync(path.join(__dirname, file), "utf8");
// The same lossless files and credits drive the development and portable pages.
const library = "试听/鸟鸣库";
const birds = JSON.parse(read(library + "/catalog.json")).clips.map((clip) => {
  const attribution = /^\(c\) (.+?), some rights reserved/.exec(clip.attribution);
  const bytes = fs.readFileSync(path.join(__dirname, library, clip.file));
  return {
    id: clip.id, species: clip.species, location: clip.location,
    credit: attribution ? "© " + attribution[1] : clip.recordist, observation: clip.observation,
    license: clip.license, licenseUrl: clip.licenseUrl,
    audio: "data:audio/flac;base64," + bytes.toString("base64"),
  };
});
const libraryScript = "// Generated by build.cjs from the credited FLAC library.\n" +
  "const campusBirdLibrary = [\n" + birds.map((b) => "  " + JSON.stringify(b)).join(",\n") + "\n];\n" +
  "for (const clip of campusBirdLibrary) campusRecordings[clip.id] = clip.audio;\n";
fs.writeFileSync(path.join(__dirname, "assets/bird-recordings.js"), libraryScript);
let html = read("index.html");
html = html.replace(/(<img\b[^>]*\bsrc=")(assets\/[^"]+\.webp)"/g, (_, start, file) => {
  const image = fs.readFileSync(path.join(__dirname, file)).toString("base64");
  return start + "data:image/webp;base64," + image + '"';
});
html = html.replace(
  /<link\s+rel="stylesheet"\s+href="([^"]+)"\s*\/?>/g,
  (_, file) => "<style>\n" + read(file) + "\n</style>",
);
html = html.replace(/<script\s+src="([^"]+)"><\/script>/g, (_, file) => {
  const script = read(file).replace(/<\/script/gi, "<\\/script");
  return "<script>\n" + script + "\n</script>";
});
fs.writeFileSync(path.join(__dirname, "hujiang.html"), html);
